"""Generate static/dynamic region masks for RadarOcc K-Radar occupancy evaluation.

This tool intentionally does NOT read raw radar tensors (arrDREA).  It reuses the
processed annotations produced by ``tools/process_kradar.py``:

    <data_root>/<clip>/bbox/bbox{frame}.npy
    <data_root>/<clip>/bbox/bbox_token{frame}.npy
    <data_root>/<clip>/bbox/object_category{frame}.npy
    <data_root>/<clip>/pose/lidar_ego_pose{frame}.npy

The motion state of each tracked object is estimated from the trajectory of its
3D-box centre after transforming that centre into the common/world coordinate
system with the LiDAR ego pose.  A short local linear fit is used instead of a
single two-frame difference to reduce annotation jitter.

Output per frame:

    motion_region_gt/motion_region_gt{frame}.npy

The dense mask is aligned with the final RadarOcc occupancy grid and uses:

    0   = static evaluation region
    1   = moving-object region
    255 = ignore / uncertain / outside radar FoV

The whole current 3D box is marked as a motion *region*.  It is NOT filled as
occupied ground truth; occupancy still comes from semantic_occupancy_gt_fov.
This keeps motion annotation and occupancy annotation separate.

A per-object CSV and per-frame NPZ metadata are also written to ``motion_meta``
for threshold inspection and debugging.

Typical usage from the repository root:

    python tools/generate_motion_region_gt.py \
        --data-root /mnt/data/DataSet/K-RadarOOC/train \
        --config tools/config.yaml \
        --clips 11 \
        --frame-period 0.1

IMPORTANT: ``--frame-period`` must match the temporal spacing of the processed
bbox/pose sequence.  The script deliberately requires it instead of silently
assuming a K-Radar frame rate.
"""

from __future__ import annotations

import argparse
import csv
import os
import re
from collections import defaultdict
from dataclasses import dataclass
from typing import Dict, List, Optional, Sequence, Tuple

import numpy as np
import torch
import yaml
from mmcv.ops.points_in_boxes import points_in_boxes_cpu
from tqdm import tqdm


STATIC = np.uint8(0)
MOVING = np.uint8(1)
IGNORE = np.uint8(255)

STATE_NAME = {
    int(STATIC): "static",
    int(MOVING): "moving",
    int(IGNORE): "uncertain",
}


@dataclass
class TrackObservation:
    frame: int
    center_world: np.ndarray  # (3,)


@dataclass
class MotionEstimate:
    state: np.uint8
    speed: float
    vx: float
    vy: float
    n_obs: int
    fit_rmse: float


